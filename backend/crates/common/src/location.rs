macro_rules! labeled_enum {
    (@enum $name:ident { $($variant:ident => $label:literal,)* }) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
        #[serde(rename_all = "camelCase")]
        pub enum $name {
            $($variant),*
        }

        impl $name {
            pub const ALL: &[Self] = &[$(Self::$variant),*];

            pub fn label(self) -> &'static str {
                match self {
                    $(Self::$variant => $label),*
                }
            }
        }
    };
    ($name:ident { $($variant:ident => $label:literal $(aliases [$($alias:literal),*])?,)* }) => {
        labeled_enum!(@enum $name { $($variant => $label,)* });

        impl $name {
            pub fn from_label(label: &str) -> Option<Self> {
                match label {
                    $($label $($(| $alias)*)? => Some(Self::$variant),)*
                    _ => None,
                }
            }
        }
    };
    ($name:ident, $parent_fn:ident -> $parent:ident { $($variant:ident => $label:literal $(aliases [$($alias:literal),*])? in $parent_variant:ident,)* }) => {
        labeled_enum!(@enum $name { $($variant => $label,)* });

        impl $name {
            pub fn $parent_fn(self) -> $parent {
                match self {
                    $(Self::$variant => $parent::$parent_variant),*
                }
            }

            pub fn from_label(parent: $parent, label: &str) -> Option<Self> {
                match (parent, label) {
                    $(($parent::$parent_variant, $label $($(| $alias)*)?) => Some(Self::$variant),)*
                    _ => None,
                }
            }
        }
    };
}

macro_rules! locations {
    ($($country:ident => $country_label:literal $(aliases [$($country_alias:literal),*])? $({$(
        $region:ident => $region_label:literal $(aliases [$($region_alias:literal),*])? $({$(
            $municipality:ident => $municipality_label:literal $(aliases [$($municipality_alias:literal),*])?,
        )*})?,
    )*})?,)*) => {
        labeled_enum!(Country { $($country => $country_label $(aliases [$($country_alias),*])?,)* });
        labeled_enum!(Region, country -> Country {
            $($($($region => $region_label $(aliases [$($region_alias),*])? in $country,)*)?)*
        });
        labeled_enum!(Municipality, region -> Region {
            $($($($($($municipality => $municipality_label $(aliases [$($municipality_alias),*])? in $region,)*)?)*)?)*
        });

        impl ExecutionPlace {
            pub const ALL: &[Self] = &[
                $(Self::Country(Country::$country),)*
                $($($(Self::Region(Region::$region),)*)?)*
                $($($($($(Self::Municipality(Municipality::$municipality),)*)?)*)?)*
            ];
        }

        // Enum to fail to compile on duplicate ids (e.g. country and municipality Cuba)
        #[allow(dead_code)]
        enum UniqueIds {
            $($country,)*
            $($($($region,)*)?)*
            $($($($($($municipality,)*)?)*)?)*
        }
    };
}

